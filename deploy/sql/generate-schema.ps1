# Regenerates 02-schema.sql from the EF Core migrations. Run from any folder after adding a migration:
#   pwsh deploy/sql/generate-schema.ps1      (or: powershell -File deploy/sql/generate-schema.ps1)
# The script is idempotent: each migration runs only if it is not yet in [rasid].[__EFMigrationsHistory].
$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$target = Join-Path $PSScriptRoot '02-schema.sql'
$generated = Join-Path ([IO.Path]::GetTempPath()) 'rasid-schema.generated.sql'

Push-Location $root
try {
    dotnet tool restore | Out-Null
    dotnet ef migrations script --idempotent `
        --project src/backend/Rasid.Infrastructure `
        --startup-project src/backend/Rasid.Api `
        --output $generated
    if ($LASTEXITCODE -ne 0) { throw 'dotnet ef migrations script failed' }
}
finally {
    Pop-Location
}

# sqlcmd starts with QUOTED_IDENTIFIER OFF; filtered indexes need it ON (SSMS sets it by default).
$header = @(
    '/*'
    '  Rasid - step 2 of 3: tables, indexes and keys (schemas rasid and auth). Generated by generate-schema.ps1,'
    '  do not edit by hand. Idempotent: applies only the migrations the database does not have yet.'
    ''
    '    sqlcmd -S <server> -E -C -b -d Rasid -i 02-schema.sql'
    '*/'
    'SET QUOTED_IDENTIFIER ON;'
    'SET ANSI_NULLS ON;'
    'GO'
    ''
)
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($target, (($header -join "`r`n") + "`r`n" + [IO.File]::ReadAllText($generated)), $utf8)
Remove-Item $generated
Write-Host "Wrote $target"
